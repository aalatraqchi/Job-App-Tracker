[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$runId = [Guid]::NewGuid().ToString('N').Substring(0, 12)
$fixtureDatabase = "job_app_tracker_verify_$runId"
$restoredDatabase = "job_app_tracker_restore_fixture_$runId"
$personalRestore = "job_app_tracker_restore_personal_$runId"
$invalidRestore = "job_app_tracker_restore_invalid_$runId"
$createdDatabases = [Collections.Generic.List[string]]::new()
$testDirectory = Join-Path (Split-Path $PSScriptRoot -Parent) "target/backup-verification-$runId"

function Invoke-DatabaseSql([string]$Database, [string]$Sql) {
    $result = & docker compose exec -T database psql -X -U job_app_tracker -d $Database `
        -At -v ON_ERROR_STOP=1 -c $Sql
    if ($LASTEXITCODE -ne 0) { throw "Verification SQL failed in $Database." }
    return $result
}

function Assert-Rejected([scriptblock]$Action, [string]$Message) {
    $rejected = $false
    try { $null = & $Action } catch { $rejected = $true }
    if (-not $rejected) { throw "Expected rejection: $Message" }
    Write-Host "PASS: $Message"
}

$fingerprintSql = @'
SELECT md5(jsonb_build_object(
    'applications', (SELECT coalesce(jsonb_agg(to_jsonb(a) ORDER BY id), '[]'::jsonb) FROM job_applications a),
    'interviews', (SELECT coalesce(jsonb_agg(to_jsonb(i) ORDER BY id), '[]'::jsonb) FROM interview_stages i)
)::text);
'@

Push-Location (Split-Path $PSScriptRoot -Parent)
try {
    $null = New-Item -ItemType Directory -Path $testDirectory -Force
    $personalBefore = Invoke-DatabaseSql 'job_app_tracker' $fingerprintSql
    $personalBackup = & "$PSScriptRoot/backup-database.ps1"
    $null = & "$PSScriptRoot/restore-database.ps1" -BackupFile $personalBackup -Database $personalRestore
    $createdDatabases.Add($personalRestore)
    if ((Invoke-DatabaseSql $personalRestore $fingerprintSql) -ne $personalBefore) {
        throw 'Personal backup differs from its source snapshot; stop writes and rerun verification.'
    }
    Write-Host 'PASS: real personal archive restores matching application/interview data into a separate database.'

    & docker compose exec -T database createdb -U job_app_tracker --template=template0 $fixtureDatabase
    if ($LASTEXITCODE -ne 0) { throw 'Could not create the disposable fixture database.' }
    $createdDatabases.Add($fixtureDatabase)
    $null = Invoke-DatabaseSql $fixtureDatabase @'
CREATE TABLE job_applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company varchar(200) NOT NULL, position varchar(200) NOT NULL,
    applied_date date NOT NULL, status varchar(20) NOT NULL,
    job_url varchar(2000), notes varchar(5000)
);
CREATE TABLE interview_stages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id bigint NOT NULL REFERENCES job_applications(id),
    stage_name varchar(200) NOT NULL, scheduled_at timestamptz,
    outcome varchar(20) NOT NULL, notes varchar(5000)
);
INSERT INTO job_applications (company, position, applied_date, status, job_url, notes)
VALUES (U&'Caf\00E9', 'Java Developer', '2026-10-08', 'INTERVIEW', 'https://example.com/job', E'First line\nSecond line'),
       ('Optional fields', 'Developer', '2026-10-07', 'APPLIED', NULL, NULL),
       ('Deleted row', 'Developer', '2026-10-06', 'WITHDRAWN', NULL, NULL);
DELETE FROM job_applications WHERE id = 3;
INSERT INTO interview_stages (application_id, stage_name, scheduled_at, outcome, notes)
VALUES (1, 'Phone screen', '2026-10-15T14:30:00-04:00', 'PASSED', U&'R\00E9sum\00E9 reviewed'),
       (1, 'Technical interview', NULL, 'PENDING', NULL),
       (2, 'Deleted stage', NULL, 'CANCELLED', NULL);
DELETE FROM interview_stages WHERE id = 3;
'@
    $fixtureBefore = Invoke-DatabaseSql $fixtureDatabase $fingerprintSql
    $fixtureBackup = & "$PSScriptRoot/backup-database.ps1" -Database $fixtureDatabase -OutputDirectory $testDirectory
    $null = & "$PSScriptRoot/restore-database.ps1" -BackupFile $fixtureBackup -Database $restoredDatabase
    $createdDatabases.Add($restoredDatabase)
    if ((Invoke-DatabaseSql $restoredDatabase $fingerprintSql) -ne $fixtureBefore) {
        throw 'Restored fixture fields do not match.'
    }
    $nextApplication = Invoke-DatabaseSql $restoredDatabase @'
INSERT INTO job_applications (company, position, applied_date, status)
VALUES ('After restore', 'Developer', '2026-10-08', 'APPLIED') RETURNING id;
'@
    $nextInterview = Invoke-DatabaseSql $restoredDatabase @'
INSERT INTO interview_stages (application_id, stage_name, outcome)
VALUES (4, 'After restore', 'PENDING') RETURNING id;
'@
    if ($nextApplication[0] -ne '4' -or $nextInterview[0] -ne '4') {
        throw 'Identity sequence state was not preserved.'
    }
    $relationships = Invoke-DatabaseSql $restoredDatabase @'
SELECT count(*) FROM interview_stages i JOIN job_applications a ON a.id = i.application_id;
'@
    if ($relationships -ne '3') { throw 'Interview relationships were not preserved.' }
    Write-Host 'PASS: text/Unicode, dates, statuses, nulls, interview relationships, and identity sequences survive restore.'
    Assert-Rejected {
        Invoke-DatabaseSql $restoredDatabase "INSERT INTO interview_stages (application_id, stage_name, outcome) VALUES (999999, 'Invalid parent', 'PENDING');"
    } 'restored foreign key rejects an interview without a parent application'

    Assert-Rejected { & "$PSScriptRoot/restore-database.ps1" -BackupFile $fixtureBackup -Database 'job_app_tracker' } `
        'working database cannot be a restore destination'
    $beforeRejection = Invoke-DatabaseSql $restoredDatabase $fingerprintSql
    Assert-Rejected { & "$PSScriptRoot/restore-database.ps1" -BackupFile $fixtureBackup -Database $restoredDatabase } `
        'existing restore destination cannot be overwritten'
    if ((Invoke-DatabaseSql $restoredDatabase $fingerprintSql) -ne $beforeRejection) {
        throw 'Rejected overwrite changed destination data.'
    }
    $invalidFile = Join-Path $testDirectory 'invalid.dump'
    [IO.File]::WriteAllText($invalidFile, 'not a PostgreSQL archive')
    [IO.File]::WriteAllText("$invalidFile.sha256", ('0' * 64))
    Assert-Rejected { & "$PSScriptRoot/restore-database.ps1" -BackupFile $invalidFile -Database $invalidRestore } `
        'changed archive fails checksum before creating a database'
    [IO.File]::WriteAllText("$invalidFile.sha256", (Get-FileHash -LiteralPath $invalidFile -Algorithm SHA256).Hash)
    Assert-Rejected { & "$PSScriptRoot/restore-database.ps1" -BackupFile $invalidFile -Database $invalidRestore } `
        'invalid archive with matching checksum fails before creating a database'
    if (Invoke-DatabaseSql 'postgres' "SELECT 1 FROM pg_database WHERE datname = '$invalidRestore';") {
        throw 'Invalid archive unexpectedly created a database.'
    }
    if ((Invoke-DatabaseSql 'job_app_tracker' $fingerprintSql) -ne $personalBefore) {
        throw 'Working data changed during verification; check for concurrent app writes.'
    }
    Write-Host 'PASS: working application/interview data unchanged.'
    Write-Host "Verification passed. Personal backup retained: $personalBackup"
} finally {
    foreach ($databaseName in $createdDatabases) {
        # Names are generated above; never accept a user-supplied cleanup target.
        if ($databaseName -notmatch '^job_app_tracker_(verify|restore_(personal|fixture))_[a-f0-9]{12}$') {
            Write-Warning 'Unexpected cleanup name; no database was dropped.'
            continue
        }
        & docker compose exec -T database dropdb -U job_app_tracker $databaseName
        if ($LASTEXITCODE -ne 0) { Write-Warning "Could not clean up disposable database $databaseName." }
    }
    Pop-Location
}
